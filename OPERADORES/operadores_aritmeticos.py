#suma y resta(+ y -)
suma = 5 + 3
resta = 5 - 3
#multiplicacion y division(* y /)
multiplicacion = 5 * 3
division = 5 / 3 #division devuelve un dato flotante aunque sea un numero cerrado es decir 6/3=2.0
#potenciacion (exponente) (**)
potencia = 5 ** 3   
#division baja (//) devuelve un dato entero hacia abajo, es decir, redondea hacia el entero menor
division_baja = 5 // 3
#resto o modulo (%) devuelve el resto de la division
resto = 5 % 3
print(suma)
print(resta)
print(multiplicacion)
print(division)
print(potencia)
print(division_baja)
print(resto)
