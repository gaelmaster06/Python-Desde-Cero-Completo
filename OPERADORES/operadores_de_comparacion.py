#valor operador valor
es_igual_que = 5 == 3 #false lo operadores de comparacion devuelven un valor booleano, es decir, true o false
es_diferente_que = 5 != 3 #true
es_mayor_que = 5 > 3 #true
es_menor_que = 5 < 3 #false
es_mayor_o_igual_que = 5 >= 3 #true
es_menor_o_igual_que = 5 <= 3 #false

print(es_igual_que)
print(es_diferente_que)
print(es_mayor_que)
print(es_menor_que)
print(es_mayor_o_igual_que)
print(es_menor_o_igual_que)

#comparar contraseñas
contraseña_almacenada = 'hola mundo'
contraseña_ingresada = 'hola mundo'
print(contraseña_almacenada == contraseña_ingresada) #devuelve true si la contraseña ingresada es igual a la almacenada, de lo contrario devuelve false